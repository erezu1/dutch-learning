// ---------------------------------------------------------------------------
// Fetches which helper verb each Dutch verb takes in the perfect tense.
//
// The kaikki.org extract drops this, but the underlying Wiktionary markup has
// it: the {{nl-conj-*}} conjugation templates carry `aux=zijn`, and
// `trans=unacc` (unaccusative) implies zijn too. No parameter means hebben,
// which is the default.
//
// Only the verbs actually in the deck are requested, so this is a few hundred
// pages rather than another bulk download.
//
// Run:  node scripts/fetch-auxiliaries.mjs
// Then: node scripts/build-deck.mjs <data-dir>
// ---------------------------------------------------------------------------

import { readFile, writeFile } from 'node:fs/promises'

const API = 'https://en.wiktionary.org/w/api.php'
const UA = 'dutch-learning-deckbuilder/0.1 (personal study app)'
const BATCH = 50

async function fetchBatch(titles) {
  const body = new URLSearchParams({
    action: 'query',
    prop: 'revisions',
    rvprop: 'content',
    rvslots: 'main',
    format: 'json',
    formatversion: '2',
    maxlag: '5',
    titles: titles.join('|'),
  })
  const res = await fetch(API, { method: 'POST', body, headers: { 'User-Agent': UA } })
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  const data = await res.json()
  if (data.error) throw new Error(data.error.info)
  return data.query?.pages ?? []
}

/** The Dutch section only — the same spelling often exists in other languages. */
function dutchSection(text) {
  const m = text.match(/==\s*Dutch\s*==([\s\S]*?)(?=\n==[^=][\s\S]*|$)/)
  return m ? m[1] : ''
}

function auxiliaryFrom(section) {
  const templates = section.match(/\{\{nl-conj[^}]*\}\}/g)
  if (!templates?.length) return null

  let sawZijn = false
  let sawHebben = false
  for (const t of templates) {
    const aux = /\|aux=([a-z,]+)/.exec(t)?.[1]
    const trans = /\|trans=([a-z,]+)/.exec(t)?.[1]
    if (aux?.includes('zijn')) sawZijn = true
    if (aux?.includes('hebben')) sawHebben = true
    // Unaccusative verbs take zijn; ergative verbs take either.
    if (trans?.includes('unacc')) sawZijn = true
    if (trans?.includes('erg')) {
      sawZijn = true
      sawHebben = true
    }
    if (!aux && !trans) sawHebben = true
  }

  if (sawZijn && sawHebben) return 'both'
  if (sawZijn) return 'zijn'
  return 'hebben'
}

async function main() {
  const words = new Set()
  for (const file of ['deck-core.json', 'deck-a1.json', 'deck-function.json']) {
    const deck = JSON.parse(await readFile(`src/content/${file}`, 'utf8'))
    for (const n of deck.notes) if (n.pos === 'verb') words.add(n.nl)
  }
  const list = [...words].sort()
  console.log(`${list.length} verbs to look up`)

  const result = {}
  const missing = []

  for (let i = 0; i < list.length; i += BATCH) {
    const slice = list.slice(i, i + BATCH)
    let pages
    for (let attempt = 0; attempt < 3; attempt++) {
      try {
        pages = await fetchBatch(slice)
        break
      } catch (e) {
        console.warn(`  retrying (${e.message})`)
        await new Promise((r) => setTimeout(r, 2000 * (attempt + 1)))
      }
    }
    if (!pages) throw new Error('batch failed after retries')

    for (const page of pages) {
      const text = page.revisions?.[0]?.slots?.main?.content
      if (!text) {
        missing.push(page.title)
        continue
      }
      const aux = auxiliaryFrom(dutchSection(text))
      if (aux) result[page.title] = aux
      else missing.push(page.title)
    }
    process.stdout.write(`  ${Math.min(i + BATCH, list.length)}/${list.length}\r`)
    await new Promise((r) => setTimeout(r, 400)) // be a polite API citizen
  }

  const counts = Object.values(result).reduce((a, v) => ((a[v] = (a[v] ?? 0) + 1), a), {})
  const out = {
    note:
      'Which helper verb each verb takes in the perfect tense. Generated by ' +
      'scripts/fetch-auxiliaries.mjs from English Wiktionary conjugation ' +
      'templates: aux=zijn or trans=unacc means zijn, no parameter means ' +
      'hebben, and a verb with both readings is "both". Verbs absent from ' +
      'this file get no hebben/zijn card, because guessing is worse than ' +
      'not asking.',
    counts,
    missing,
    auxiliaries: Object.fromEntries(Object.entries(result).sort(([a], [b]) => a.localeCompare(b))),
  }
  await writeFile('src/content/auxiliaries.json', JSON.stringify(out, null, 1), 'utf8')
  console.log(`\nwrote ${Object.keys(result).length} verbs ->`, counts)
  console.log(`no conjugation table for ${missing.length}:`, missing.slice(0, 12))
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
